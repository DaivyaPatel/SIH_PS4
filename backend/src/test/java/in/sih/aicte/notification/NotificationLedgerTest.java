package in.sih.aicte.notification;

import static org.assertj.core.api.Assertions.assertThat;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.patch;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.zaxxer.hikari.HikariDataSource;
import in.sih.aicte.cases.ApplicationCase;
import in.sih.aicte.cases.ApplicationCaseRepository;
import io.zonky.test.db.postgres.embedded.EmbeddedPostgres;
import java.io.IOException;
import java.time.Instant;
import java.time.temporal.ChronoUnit;
import java.util.UUID;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.web.servlet.AutoConfigureMockMvc;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.boot.test.context.TestConfiguration;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Import;
import org.springframework.http.MediaType;
import org.springframework.test.annotation.DirtiesContext;
import org.springframework.test.web.servlet.MockMvc;

@SpringBootTest
@AutoConfigureMockMvc
@DirtiesContext(classMode = DirtiesContext.ClassMode.AFTER_CLASS)
@Import(NotificationLedgerTest.TestInfrastructure.class)
class NotificationLedgerTest {

    @Autowired MockMvc mvc;
    @Autowired ObjectMapper mapper;
    @Autowired ApplicationCaseRepository caseRepository;
    @Autowired NotificationRepository notificationRepository;

    @TestConfiguration(proxyBeanMethods = false)
    static class TestInfrastructure {
        @Bean(destroyMethod = "close")
        EmbeddedPostgres postgres() throws IOException {
            return EmbeddedPostgres.builder().setPort(0).setServerConfig("listen_addresses", "127.0.0.1").start();
        }

        @Bean(destroyMethod = "close")
        HikariDataSource datasource(EmbeddedPostgres postgres) {
            var pool = new HikariDataSource();
            pool.setJdbcUrl(postgres.getJdbcUrl("postgres", "postgres"));
            pool.setUsername("postgres");
            pool.setPassword("");
            return pool;
        }
    }

    @Test
    void seededNotificationsAreRetrievableWithFiltering() throws Exception {
        mvc.perform(get("/api/v1/notifications"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.length()").value(org.hamcrest.Matchers.greaterThanOrEqualTo(7)));

        UUID case2Id = UUID.fromString("33333333-3333-3333-3333-333333333002");
        mvc.perform(get("/api/v1/notifications?caseId=" + case2Id))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.length()").value(2))
                .andExpect(jsonPath("$[0].caseId").value(case2Id.toString()));

        mvc.perform(get("/api/v1/notifications?type=DEFICIENCY_NOTICE"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$[0].notificationType").value("DEFICIENCY_NOTICE"));

        mvc.perform(get("/api/v1/notifications?recipientRole=REGIONAL_OFFICER"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$[0].recipientRole").value("REGIONAL_OFFICER"));
    }

    @Test
    void markNotificationAsReadUpdatesStatusAndTimestamp() throws Exception {
        UUID noticeId = UUID.fromString("99999999-9999-9999-9999-999999999001");

        mvc.perform(patch("/api/v1/notifications/" + noticeId + "/read"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.id").value(noticeId.toString()))
                .andExpect(jsonPath("$.isRead").value(true))
                .andExpect(jsonPath("$.status").value("READ"))
                .andExpect(jsonPath("$.readAt").isNotEmpty());

        Notification updated = notificationRepository.findById(noticeId).orElseThrow();
        assertThat(updated.isRead()).isTrue();
        assertThat(updated.getStatus()).isEqualTo(NotificationStatus.READ);
        assertThat(updated.getReadAt()).isNotNull();
    }

    @Test
    void escalationAutoGeneratedForOverdueCase() throws Exception {
        UUID case1Id = UUID.fromString("33333333-3333-3333-3333-333333333001");
        ApplicationCase case1 = caseRepository.findById(case1Id).orElseThrow();
        case1.setDeadlineAt(Instant.now().minus(2, ChronoUnit.DAYS));
        caseRepository.save(case1);

        mvc.perform(post("/api/v1/notifications/escalate-check"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.overdueCasesFound").value(org.hamcrest.Matchers.greaterThanOrEqualTo(1)))
                .andExpect(jsonPath("$.escalationsCreated").value(org.hamcrest.Matchers.greaterThanOrEqualTo(1)))
                .andExpect(jsonPath("$.newEscalations[0].priority").value("CRITICAL"))
                .andExpect(jsonPath("$.newEscalations[0].notificationType").value("ESCALATION"));

        mvc.perform(post("/api/v1/notifications/escalate-check"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.escalationsCreated").value(0));
    }

    @Test
    void manualNotificationCreationSucceeds() throws Exception {
        UUID caseId = UUID.fromString("33333333-3333-3333-3333-333333333004");
        NotificationDto.CreateNotificationRequest request = new NotificationDto.CreateNotificationRequest(
                caseId,
                null,
                NotificationRecipientRole.EVC_EXPERT,
                "expert.sharma@iitd.ac.in",
                NotificationChannel.EMAIL,
                NotificationType.INSPECTION_APPOINTMENT,
                "EVC Assignment: National Polytechnic Inspection Roster",
                "You have been assigned to the 3-member committee visiting Chennai campus on 2026-11-04.",
                NotificationPriority.HIGH,
                "{\"appointmentDate\":\"2026-11-04\"}"
        );

        mvc.perform(post("/api/v1/notifications")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content(mapper.writeValueAsString(request)))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.recipientContact").value("expert.sharma@iitd.ac.in"))
                .andExpect(jsonPath("$.notificationType").value("INSPECTION_APPOINTMENT"))
                .andExpect(jsonPath("$.priority").value("HIGH"))
                .andExpect(jsonPath("$.applicationNumber").value("APP-2026-SRO-004"));
    }

    @Test
    void summaryEndpointProvidesAccurateMetrics() throws Exception {
        mvc.perform(get("/api/v1/notifications/summary"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.total").value(org.hamcrest.Matchers.greaterThanOrEqualTo(7)))
                .andExpect(jsonPath("$.unread").value(org.hamcrest.Matchers.greaterThanOrEqualTo(1)))
                .andExpect(jsonPath("$.deficiencyNotices").value(org.hamcrest.Matchers.greaterThanOrEqualTo(2)));
    }

    @Test
    void invalidTypeQueryParamReturns400Problem() throws Exception {
        mvc.perform(get("/api/v1/notifications?type=INVALID_NOTIFICATION_TYPE"))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.status").value(400))
                .andExpect(jsonPath("$.title").value("Invalid parameter"));
    }
}
